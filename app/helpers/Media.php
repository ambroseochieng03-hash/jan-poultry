<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Media URLs and cleanup
|--------------------------------------------------------------------------
| MEDIA_DRIVER=r2     -> files live in Cloudflare R2, served from MEDIA_BASE_URL
| MEDIA_DRIVER=local  -> legacy/dev: files live in public/uploads/products
*/
final class Media
{
    public const PLACEHOLDER = '/assets/img/no-image.svg';

    public static function driver(): string
    {
        return Env::get('MEDIA_DRIVER', 'local') === 'r2' ? 'r2' : 'local';
    }

    /** Folder URL without trailing slash, e.g. https://jpmedia.luxempire.co.ke/products */
    public static function baseUrl(): string
    {
        if (self::driver() === 'r2') {
            return rtrim((string) Env::get('MEDIA_BASE_URL', ''), '/') . '/products';
        }

        return '/uploads/products';
    }

    public static function url(?string $file): string
    {
        $file = basename(trim((string) $file));

        return $file === '' ? self::PLACEHOLDER : self::baseUrl() . '/' . rawurlencode($file);
    }

    public static function isVideo(?string $file): bool
    {
        return strtolower(pathinfo((string) $file, PATHINFO_EXTENSION)) === 'mp4';
    }

    /** Small preview of an image (generated by the worker). Falls back to the full file. */
    public static function thumbUrl(?string $file): string
    {
        $file = basename(trim((string) $file));

        if (self::driver() === 'r2' && str_ends_with($file, '.webp')) {
            return self::url(substr($file, 0, -5) . '_thumb.webp');
        }

        return self::url($file);
    }

    /** Poster frame of a video (generated by the worker). */
    public static function posterUrl(?string $file): string
    {
        $file = basename(trim((string) $file));

        if (self::driver() === 'r2' && str_ends_with($file, '.mp4')) {
            return self::url(substr($file, 0, -4) . '_poster.webp');
        }

        return self::PLACEHOLDER;
    }

    /** Every object a product file can produce. */
    public static function variants(string $file): array
    {
        $stem = pathinfo($file, PATHINFO_FILENAME);

        return array_values(array_unique([
            $file,
            $stem . '_thumb.webp',
            $stem . '_poster.webp',
        ]));
    }

    /** Remove a product's media from R2 and from local disk. Never throws. */
    public static function delete(?string $file): void
    {
        $file = basename(trim((string) $file));

        if ($file === '') {
            return;
        }

        foreach (self::variants($file) as $variant) {

            $local = dirname(__DIR__, 2) . '/public/uploads/products/' . $variant;

            if (is_file($local)) {
                @unlink($local);
            }
        }

        if (self::driver() !== 'r2') {
            return;
        }

        try {

            require_once __DIR__ . '/../services/R2Client.php';

            $r2 = R2Client::fromEnv();

            foreach (self::variants($file) as $variant) {
                $r2->delete('products/' . $variant);
            }

        } catch (Throwable $e) {

            if (function_exists('jan_log')) {
                jan_log('WARNING', 'R2 delete failed: ' . $e->getMessage(), ['file' => $file]);
            }
        }
    }
}
